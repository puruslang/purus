import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { compilerPath, packageRoot } from "../ts/lib/paths.js";

const cli = path.join(packageRoot, "dist", "cli.cjs");
const built = fs.existsSync(compilerPath) && fs.existsSync(cli);

function run(args: string[], cwd?: string): string {
  return execFileSync(process.execPath, [cli, ...args], {
    encoding: "utf8",
    cwd,
  });
}

// Needs `npm run build` (compiler + wrapper bundle).
describe.skipIf(!built)("built package", () => {
  it("compiles through the programmatic API", async () => {
    const { compile, check, version } = await import("../ts/index.js");
    expect(version).toMatch(/^\d+\.\d+\.\d+/);
    expect(compile("const x be 42", { header: false })).toContain(
      "const x = 42;"
    );
    expect(compile("const x be 42")).toMatch(/^\/\/ Generated by Purus /);
    expect(check("const x be 42")).toBe(true);
  });

  it("reports syntax errors from check", async () => {
    const { check } = await import("../ts/index.js");
    expect(() => check("const x be 1\nx be 2")).toThrow(/Syntax error/);
  });

  it("honours the strict option", async () => {
    const { compile } = await import("../ts/index.js");
    expect(
      compile("const x be 1", { header: false, strict: false })
    ).not.toContain("use strict");
  });

  it("compiles require[...] and the commonjs type", async () => {
    const { compile } = await import("../ts/index.js");
    const js = compile("const fs be require[///fs///]", {
      header: false,
      type: "commonjs",
    });
    expect(js).toMatch(/require\("fs"\)|undefined\("fs"\)/);
  });

  it("prints the version and help", () => {
    expect(run(["version"])).toMatch(/^Purus v\d+\.\d+\.\d+/);
    expect(run(["help"])).toContain("purus build [file|dir]");
  });

  it("builds a file to stdout and writes .cjs for .cpurus", () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "purus-cli-"));
    try {
      const file = path.join(dir, "a.purus");
      fs.writeFileSync(file, "console.log[///hi///]\n");
      expect(run(["build", "--stdout", "--no-header", file])).toContain(
        'console.log("hi");'
      );

      const cjs = path.join(dir, "b.cpurus");
      fs.writeFileSync(cjs, "console.log[///cjs///]\n");
      run(["build", cjs]);
      expect(fs.existsSync(path.join(dir, "b.cjs"))).toBe(true);
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });

  it("builds a project from config.purus", () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "purus-proj-"));
    try {
      fs.mkdirSync(path.join(dir, "src"));
      fs.writeFileSync(
        path.join(dir, "config.purus"),
        "const entry be ///src///\nconst output be ///out///\n"
      );
      fs.writeFileSync(path.join(dir, "src", "main.purus"), "const a be 1\n");
      run(["build"], dir);
      expect(
        fs.readFileSync(path.join(dir, "out", "main.js"), "utf8")
      ).toContain("const a = 1;");
      expect(run(["check"], dir)).toContain("1 file checked. No errors.");
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });

  it("scaffolds with init", () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "purus-init-"));
    try {
      fs.writeFileSync(path.join(dir, "package.json"), '{"name":"t"}');
      run(["init"], dir);
      expect(fs.existsSync(path.join(dir, "config.purus"))).toBe(true);
      expect(fs.existsSync(path.join(dir, "src", "main.purus"))).toBe(true);
      const pkg = JSON.parse(
        fs.readFileSync(path.join(dir, "package.json"), "utf8")
      ) as { scripts: Record<string, string>; type: string };
      expect(pkg.type).toBe("module");
      expect(pkg.scripts.build).toBe("purus build");
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });
});
